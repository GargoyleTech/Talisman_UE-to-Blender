using CUE4Parse.UE4.Assets;
using CUE4Parse.UE4.Assets.Exports.Texture;
using CUE4Parse_Conversion.Textures;
using CUE4Parse_Conversion.Options;

/// <summary>Generic texture layouts outside conventional Texture2D mip arrays.</summary>
internal static class GenericTextureExporter
{
    public static Dictionary<string, object?>? TryExport(IPackage package, string? objectPath,
        string? output, int maxResolution, int mipOffset, bool preview = false)
    {
        var export = string.IsNullOrWhiteSpace(objectPath)
            ? package.GetExports().FirstOrDefault(item => item is UTexture || item.ExportType.StartsWith("TextureRenderTarget", StringComparison.Ordinal))
            : GenericUnreal.ResolveExport<CUE4Parse.UE4.Assets.Exports.UObject>(package, objectPath);
        if (export?.ExportType.StartsWith("TextureRenderTarget", StringComparison.Ordinal) == true)
            return new Dictionary<string, object?>
            {
                ["status"] = "unavailable", ["textureType"] = export.ExportType,
                ["unavailableReason"] = "runtime_generated",
                ["reason"] = $"{export.ExportType} is generated by the running game and has no stored image pixels to import.",
            };
        if (export is not UTexture texture) return null;
        if (texture is UVolumeTexture) return ExportVolume(texture, output, maxResolution, mipOffset, preview);
        if (texture.PlatformData is { FirstMipToSerialize: >= 0, VTData: { } vt } && vt.IsInitialized())
        {
            if (vt.NumLayers != 1)
                throw new NotSupportedException("Virtual textures with multiple image layers need an explicit layer selection.");
            // Virtual textures have tiled VTData and can have no conventional
            // mips. Select the requested level from declared dimensions
            // instead of decoding mip 0 to discover the source dimensions.
            var sizes = Enumerable.Range(0, checked((int)vt.NumMips))
                .Select(i => (Math.Max(1, checked((int)vt.Width) >> i), Math.Max(1, checked((int)vt.Height) >> i))).ToArray();
            CTexture? Decode(int index)
            {
                var decoded = texture.DecodeMip(index);
                if (decoded is null) return null;
                var (width, height) = sizes[index];
                if (decoded.Width == width && decoded.Height == height) return decoded;
                // The pinned decoder keeps a mip-0-sized canvas for legacy
                // one-tile mips. Only the top-left logical rectangle is written;
                // crop it before encoding, excluding padding/uninitialized bytes.
                if (decoded.Width < width || decoded.Height < height ||
                    !PixelFormatUtils.PixelFormats.TryGetValue(decoded.PixelFormat, out var format) ||
                    format.BlockSizeX != 1 || format.BlockSizeY != 1 || format.BlockBytes == 0)
                    throw new InvalidDataException("Virtual texture decoder returned incompatible image dimensions.");
                var pixels = new byte[checked(width * height * format.BlockBytes)];
                var rowBytes = checked(width * format.BlockBytes);
                for (var row = 0; row < height; row++)
                    decoded.Data.AsSpan(checked(row * decoded.Width * format.BlockBytes), rowBytes)
                        .CopyTo(pixels.AsSpan(row * rowBytes, rowBytes));
                return new CTexture(width, height, decoded.PixelFormat, pixels);
            }
            return ExportDecoded(texture, sizes, Decode, output,
                maxResolution, mipOffset, "VIRTUAL_2D", useDeclaredAvailability: true, preview: preview);
        }
        return null;
    }

    private static Dictionary<string, object?> ExportVolume(UTexture texture, string? output,
        int maxResolution, int mipOffset, bool preview)
    {
        var mips = texture.PlatformData.Mips;
        var sizes = mips.Select(m => (m.SizeX, checked(m.SizeY * Math.Max(1, m.SizeZ)))).ToArray();
        CTexture? Decode(int index)
        {
            var mip = texture.GetMip(index);
            if (mip?.BulkData?.Data is not { Length: > 0 } data ||
                !PixelFormatUtils.PixelFormats.TryGetValue(texture.Format, out var format)) return null;
            var required = checked((long)((mip.SizeX + format.BlockSizeX - 1) / format.BlockSizeX) *
                ((mip.SizeY + format.BlockSizeY - 1) / format.BlockSizeY) *
                ((Math.Max(1, mip.SizeZ) + format.BlockSizeZ - 1) / format.BlockSizeZ) * format.BlockBytes);
            // Some parser versions expose flattened volume dimensions on
            // lower mips without a matching payload. Never decode past it.
            if (required <= 0 || required > data.LongLength) return null;
            var decoded = texture.Decode(mip);
            return decoded is null ? null : new CTexture(decoded.Width,
                checked(decoded.Height * Math.Max(1, mip.SizeZ)), decoded.PixelFormat, decoded.Data);
        }
        // Keep every Z slice as a vertical atlas in the material inventory.
        // This preserves the pixels without pretending to recreate a 3D shader.
        return ExportDecoded(texture, sizes, Decode, output, maxResolution, mipOffset, "VOLUME_ATLAS", preview: preview);
    }

    private static Dictionary<string, object?> ExportDecoded(UTexture texture, (int Width, int Height)[] sizes,
        Func<int, CTexture?> decode, string? output, int maxResolution, int mipOffset, string layout,
        bool useDeclaredAvailability = false, bool preview = false)
    {
        var decodedMips = new Dictionary<int, CTexture?>();
        Exception? firstFailure = null;
        var sourceWidth = 0;
        var sourceHeight = 0;
        bool Read(int index)
        {
            try { decodedMips[index] = decode(index); return decodedMips[index] is { Width: > 0, Height: > 0 }; }
            catch (Exception error) { firstFailure ??= error; return false; }
        }
        var mipIndex = TextureMipSelection.Select(sizes, Read, maxResolution, mipOffset,
            useDeclaredAvailability ? _ => true : null,
            i => { sourceWidth = sizes[i].Width; sourceHeight = sizes[i].Height; });
        if (mipIndex < 0 || !decodedMips.TryGetValue(mipIndex, out var selected) || selected is null)
            throw new InvalidOperationException($"{texture.ExportType} has no readable {layout} image.", firstFailure);
        var extension = "png";
        var data = preview ? TextureBrowser.EncodePreview(selected)
            : TextureEncoder.Encode(selected, ETextureFormat.Png, true, out extension);
        if (data.Length == 0) throw new InvalidOperationException($"Texture decoder returned an empty {extension} image.");
        if (!string.IsNullOrWhiteSpace(output))
        {
            output = Path.ChangeExtension(output, extension);
            File.WriteAllBytes(Path.GetFullPath(output), data);
        }
        return new Dictionary<string, object?>
        {
            ["status"] = "ready", ["textureType"] = texture.ExportType, ["textureLayout"] = layout,
            ["width"] = selected.Width, ["height"] = selected.Height,
            ["sourceWidth"] = sourceWidth, ["sourceHeight"] = sourceHeight,
            ["mipIndex"] = mipIndex, ["pixelFormat"] = texture.Format.ToString(),
            ["srgb"] = texture.SRGB, ["fileExtension"] = extension,
            ["byteLength"] = data.Length, ["output"] = output,
        };
    }
}
